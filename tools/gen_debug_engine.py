ABILITIES_OUT = "abilities_traced.py"


class PatchError(RuntimeError):
    pass


def apply_patches(text: str, patches, source_name: str) -> str:
    for name, old, new in patches:
        count = text.count(old)
        if count != 1:
            raise PatchError(
                f"[FAIL] {source_name}: patch '{name}' anchor found {count} times (expected 1). "
                "The real engine changed; update tools/gen_debug_engine.py."
            )
        text = text.replace(old, new)
    return text


def _read_normalized(source_name: str) -> tuple[str, str]:
    raw = (SRC / source_name).read_bytes()
    digest = hashlib.sha256(raw.replace(b"\r\n", b"\n")).hexdigest()[:12]
    return raw.decode("utf-8").replace("\r\n", "\n"), digest


def build(source_name: str, patches) -> str:
    """Returns the generated module text (LF newlines) for one real module."""
    text, digest = _read_normalized(source_name)
    return HEADER.format(source=f"src/swtorsim/{source_name}", digest=digest) + apply_patches(text, patches, source_name)


def extract_method(text: str, start: str, end: str, label: str) -> str:
    if text.count(start) != 1 or text.count(end) != 1:
        raise PatchError(f"[FAIL] abilities.py: could not locate {label} (start/end marker not unique).")
    begin = text.index(start)
    finish = text.index(end, begin)
    return text[begin:finish].rstrip("\n") + "\n"


def build_abilities_traced() -> str:
    """Returns the generated abilities_traced.py text: the patched methods as top-level functions."""
    text, digest = _read_normalized("abilities.py")
    header = HEADER.format(source="src/swtorsim/abilities.py", digest=digest)
    header += (
        "# NOT importable on its own: traced_run.py executes this file with the globals of src.swtorsim.abilities.\n"
        "# Functions: branch_execute (Branch.execute), effect_execute_triggered_branches\n"
        "# (Effect.execute_triggered_branches).\n\n"
    )
    parts = []
    names = {"Branch.execute": "branch_execute", "Effect.execute_triggered_branches": "effect_execute_triggered_branches"}
    for source_name, start, end, patches, label in METHOD_TARGETS:
        body = extract_method(text, start, end, label)
        body = apply_patches(body, patches, f"{source_name} {label}")
        body = textwrap.dedent(body)
        method_name = label.split(".")[1]
        body = body.replace(f"def {method_name}(", f"def {names[label]}(", 1)
        parts.append(body)
    return header + "\n\n".join(parts)


def generated_files() -> dict[Path, str]:
    files = {OUT_DIR / out_name: build(src_name, patches) for src_name, out_name, patches in TARGETS}
    files[OUT_DIR / ABILITIES_OUT] = build_abilities_traced()
    files[OUT_DIR / COMBAT_MATH_OUT] = build_combat_math_traced()
    return files


def write_all() -> None:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    init = OUT_DIR / "__init__.py"
    if not init.exists():
        init.write_bytes(b'"""Generated traced copies of engine modules (see tools/gen_debug_engine.py)."""\r\n')
    for path, text in generated_files().items():
        path.write_bytes(text.replace("\n", "\r\n").encode("utf-8"))
        print(f"[OK] Wrote {path.relative_to(ROOT)}")


def is_up_to_date() -> bool:
    for path, text in generated_files().items():
        if not path.is_file() or path.read_bytes().decode("utf-8").replace("\r\n", "\n") != text:
            return False
    return True


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate the traced debug copy of the engine.")
    parser.add_argument("--check", action="store_true", help="Only verify the generated files are current.")
    args = parser.parse_args()
    try:
        if args.check:
            if is_up_to_date():
                print("[OK] Generated debug engine is up to date.")
                return 0
            print("[FAIL] Generated debug engine is stale; run tools/gen_debug_engine.py.")
            return 1
        write_all()
        return 0
    except PatchError as exc:
        print(exc)
        return 1


if __name__ == "__main__":
    sys.exit(main())
