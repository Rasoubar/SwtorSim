def build_combat_math_traced() -> str:
    """Returns the generated combat_math_traced.py text: the patched hit functions at module level."""
    text, digest = _read_normalized("combat_math.py")
    header = HEADER.format(source="src/swtorsim/combat_math.py", digest=digest)
    header += (
        "# NOT importable on its own: traced_run.py executes this file with a copy of the globals of\n"
        "# src.swtorsim.combat_math, and only events.calculate_hit is rebound to the copy for debug runs.\n\n"
    )
    parts = [COMBAT_MATH_PREAMBLE.rstrip("\n") + "\n"]
    for start, end, patches, label in COMBAT_MATH_FUNCTIONS:
        body = extract_method(text, start, end, label)
        parts.append(apply_patches(body, patches, f"combat_math.py {label}"))
    return header + "\n\n".join(parts)

