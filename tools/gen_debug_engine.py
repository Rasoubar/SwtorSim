r"""Generates the traced copy of the engine used by the web debugger.

The real engine files are never edited. This script reads them, applies anchored text patches that only add
logging (no change to control flow or to the number of random draws), and writes the result under
src/swtorsim/debug/generated/. Every patch anchor must match exactly once, so a change to the real engine that
moves an anchor makes this script (and tests/test_debug_traced_triggers.py) fail loudly instead of letting the
copy drift.

Two kinds of output:
  * triggers_traced.py - a whole-module copy of triggers.py (imported as a normal module).
  * abilities_traced.py - patched copies of two abilities.py methods (Branch.execute and
    Effect.execute_triggered_branches). They are executed with the globals of the real abilities module by
    src/swtorsim/debug/traced_run.py, so the file is not importable on its own.

Usage:
    .\tools\pyclean.exe tools\gen_debug_engine.py            # regenerate
    .\tools\pyclean.exe tools\gen_debug_engine.py --check    # exit 1 if the generated files are stale
"""

