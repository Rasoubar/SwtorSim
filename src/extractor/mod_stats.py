def _labels_from_client_gom(path: Path) -> dict[str, str] | None:
    try:
        client_gom = load_client_gom(path)
    except (OSError, ValueError):
        return None
    members = client_gom.enum_members.get(MOD_STAT_ENUM_ID)
    if not members:
        return None
    return {str(index): member for index, member in enumerate(members, 1)}


_STAT_LABELS: dict[str, str] | None = None


def load_stat_labels() -> dict[str, str]:
    candidate_paths = [
        WORK_DIR / "resources" / "systemgenerated" / "client.gom",
        DATA_DIR / "client.gom",
    ]
    for path in candidate_paths:
        labels = _labels_from_client_gom(path)
        if labels:
            return labels
    return dict(EMBEDDED_STAT_LABELS)


def get_stat_labels() -> dict[str, str]:
    global _STAT_LABELS
    if _STAT_LABELS is None:
        _STAT_LABELS = load_stat_labels()
    return _STAT_LABELS


def decode_stat_name(raw: Any, labels: dict[str, str] | None = None) -> str:
    if labels is None:
        labels = get_stat_labels()
    key = str(raw)
    if key.isdigit():
        return labels.get(key, f"STAT_unknown_{key}")
    return key
